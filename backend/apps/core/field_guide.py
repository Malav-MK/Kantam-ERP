def field_guide(resource_key, name, field_type="text", existing=""):
    """Reference text for one input: its own note (if any), what to enter, and the decimal rule."""
    text = GUIDE.get(f"{resource_key.split('.')[-1]}:{name}") or GUIDE.get(name, "")
    parts = [existing.strip()] if existing and existing.strip() else []
    if text and text not in parts:
        parts.append(text)
    if field_type in NUMBER_TYPES:
        parts.append(DECIMAL_NOTE)
    return " ".join(parts)
