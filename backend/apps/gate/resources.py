def require_photo(obj, purpose, label):
    if not attachments_for(obj, purpose).exists():
        raise BusinessRuleError(f"{label} photo/document evidence is required first (purpose '{purpose}').", "evidence_required")


class GateResource(Resource):
    module = "gate"
    closed_states = set()
    evidence_class = "security"

    def attachment_policy(self, request, obj, purpose):
        if getattr(obj, "status", None) in self.closed_states:
            return {"blocked": "This record is closed; evidence is locked."}
        return {"classification": self.evidence_class}


