class GatePassResource(GateResource):
    key = "gate.gatepass"
    server_defaults = ["asset_owner"]
    model = GatePass
    label = "Returnable / non-returnable passes"
    singular = "Gate pass"
    closed_states = {"returned", "disposed", "cancelled"}
    list_fields = ["doc_no", "returnable", "asset_description", "asset_ref", "qty", "returned_qty", "recipient", "due_back", "status", "asset_owner"]
    form_fields = ["returnable", "asset_description", "asset_ref", "mould", "qty", "recipient", "purpose", "due_back", "asset_owner"]
    readonly_fields = ["approved_by", "out_at", "return_log", "disposition"]
    filter_fields = ["status", "returnable"]
    search_fields = ["doc_no", "asset_description", "asset_ref", "recipient"]
    help = {"boundary": "A pass closes only when the balance is returned or an authorised disposition is posted."}

    def before_create(self, request, data):
        data.setdefault("asset_owner", request.user)
        if data.get("returnable") and not data.get("due_back"):
            raise BusinessRuleError("Returnable passes need a due-back date.", "validation")

    def edit_block_reason(self, request, obj):
        return None if obj.status == "draft" else f"Pass is {obj.get_status_display()}."

    def _approve(request, obj, data):
        if obj.created_by_id == request.user.pk:
            raise BusinessRuleError("Maker/checker: another authorised person must approve.", "self_approval")
        obj.status = "approved"
        obj.approved_by = request.user
        obj.save()
        audit.record("gatepass_approved", "gate.gatepass", obj)
        return obj

    def _out(request, obj, data):
        require_photo(obj, "out_photo", "Outgoing item")
        obj.status = "out"
        obj.out_at = timezone.now()
        obj.save()
        if obj.mould_id:
            type(obj.mould).objects.filter(pk=obj.mould_id).update(status="out")
        if not obj.returnable:
            obj.status = "disposed"
            obj.disposition = "Non-returnable - closed at gate-out"
            obj.save()
        audit.record("gatepass_out", "gate.gatepass", obj)
        return obj

    def _return(request, obj, data):
        qty = Decimal(str(data.get("qty") or 0))
        if qty <= 0 or obj.returned_qty + qty > obj.qty:
            raise BusinessRuleError(f"Return quantity must be within the open balance {obj.qty - obj.returned_qty}.", "invalid_qty")
        obj.returned_qty += qty
        obj.return_log = obj.return_log + [{"at": timezone.now().isoformat(), "qty": str(qty), "condition": data.get("condition", ""), "by": request.user.full_name}]
        obj.status = "returned" if obj.returned_qty >= obj.qty else "partial"
        obj.save()
        if obj.status == "returned" and obj.mould_id:
            type(obj.mould).objects.filter(pk=obj.mould_id).update(status="in_repair" if "damage" in data.get("condition", "").lower() else "available")
        audit.record("gatepass_return", "gate.gatepass", obj, changes={"qty": str(qty), "condition": data.get("condition", "")})
        return obj

    def _dispose(request, obj, data):
        obj.status = "disposed"
        obj.disposition = data["reason"]
        obj.save()
        audit.record("gatepass_disposed", "gate.gatepass", obj, reason=data["reason"])
        return obj

    actions = [
        Action("approve", "Approve pass", _approve, tone="primary", available=lambda o, r: o.status == "draft"),
        Action("out", "Record gate-out", _out, available=lambda o, r: o.status == "approved"),
        Action("return", "Record return", _return, fields=[{"name": "qty", "label": "Quantity returned", "type": "decimal", "required": True},
                                                          {"name": "condition", "label": "Condition / damage", "type": "text"}],
               available=lambda o, r: o.returnable and o.status in {"out", "partial"}),
        Action("dispose", "Authorised disposition", _dispose, permission="gate.gatepass.approve", reason_required=True, tone="danger",
               available=lambda o, r: o.status in {"out", "partial"}),
    ]


def _courier_ack(request, obj, data):
    if obj.receiver_id != request.user.pk:
        raise BusinessRuleError("Only the named receiver can acknowledge custody.", "not_authorised")
    if obj.direction != "in" or obj.status != "received":
        raise BusinessRuleError("Nothing to acknowledge.", "invalid_state")
    require_photo(obj, "parcel", "Parcel")
    obj.status = "acknowledged"
    obj.acknowledged_at = timezone.now()
    obj.outcome = data.get("outcome", "")
    obj.save()
    audit.record("courier_acknowledged", "gate.courier", obj, changes={"outcome": obj.outcome})
    return obj


@register
class CourierResource(GateResource):
    key = "gate.courier"
    model = Courier
    label = "Couriers"
    singular = "Courier"
    closed_states = {"acknowledged", "collected"}
    evidence_class = "internal"
    list_fields = ["doc_no", "direction", "courier_company", "awb", "sender", "receiver", "packages", "status", "created_at"]
    create_only_fields = ["direction"]
    form_fields = ["courier_company", "awb", "sender", "receiver", "packages", "declared_contents", "condition"]
    filter_fields = ["status", "direction", "receiver"]
    search_fields = ["doc_no", "awb", "sender"]
    help = {"boundary": "A parcel is not inventory. The receiver decides whether it becomes a sample, document, asset or stock receipt."}

    def before_create(self, request, data):
        data["guard"] = request.user
        data["status"] = "received" if data["direction"] == "in" else "awaiting_pickup"

    def after_create(self, request, obj):
        if obj.direction == "in":
            notify([obj.receiver], f"Courier for you: {obj.courier_company} {obj.awb}", severity="info", resource="gate.mycourier",
                   object_id=obj.pk, next_action="Collect from gate and acknowledge", dedupe_key=f"courier:{obj.pk}")

    def edit_block_reason(self, request, obj):
        return "Closed." if obj.status in self.closed_states else None

    def _collect(request, obj, data):
        if obj.direction != "out" or obj.status != "awaiting_pickup":
            raise BusinessRuleError("Not an outward parcel awaiting pickup.", "invalid_state")
        require_photo(obj, "parcel", "Parcel / collection proof")
        obj.status = "collected"
        obj.collected_at = timezone.now()
        obj.save()
        audit.record("courier_collected", "gate.courier", obj)
        return obj

    actions = [
        Action("collect", "Record courier collection", _collect, permission="gate.courier.release", available=lambda o, r: o.direction == "out" and o.status == "awaiting_pickup"),
    ]


