class VisitResource(GateResource):
    key = "gate.visit"
    model = Visit
    label = "Visitor book"
    singular = "Visit"
    closed_states = {"exited", "cancelled", "rejected", "no_show"}
    list_fields = ["doc_no", "visitor_name", "organisation", "visit_type", "host", "status", "expected_at", "entry_at", "exit_at", "badge_no"]
    form_fields = ["visitor_name", "organisation", "contact_phone", "person", "visit_type", "host", "purpose", "pre_registered", "expected_at",
                   "expected_minutes", "gate", "permitted_area", "escort_required", "badge_no", "safety_briefing_ack", "belongings_declared",
                   "verification_outcome", "late_stay_reason"]
    readonly_fields = ["approved_by", "decision_at", "decision_note", "entry_guard", "exit_guard", "badge_returned"]
    filter_fields = ["status", "host", "visit_type"]
    search_fields = ["doc_no", "visitor_name", "organisation", "badge_no"]
    field_permissions = {"contact_phone": PERSONAL}
    help = {
        "steps": "Create at gate -> photo & purpose -> request host approval -> host approves -> badge / escort -> entry -> exit & badge return.",
        "boundary": "The guard records and requests; the assigned host approves. Guards cannot approve their own entries.",
    }

    APPROVED_FIELDS = {"visitor_name", "organisation", "person", "visit_type", "host", "purpose", "permitted_area", "escort_required", "expected_at"}

    def edit_block_reason(self, request, obj):
        return f"Visit is {obj.get_status_display()}." if obj.status in self.closed_states | {"inside"} else None

    def before_update(self, request, obj, data):
        # What the host approved cannot be changed afterwards at the gate (business-logic integrity).
        if obj.status in {"awaiting_approval", "approved"}:
            changed = {k for k, v in data.items() if k in self.APPROVED_FIELDS and v != getattr(obj, k)}
            if changed:
                raise BusinessRuleError(f"Approved details cannot be changed ({', '.join(sorted(changed))}). Cancel and create a new visit.",
                                        "approved_fields_locked")

    def _request(request, obj, data):
        require_photo(obj, "visitor_photo", "Visitor")
        obj.status = "awaiting_approval"
        obj.row_version += 1
        obj.save()
        notify([obj.host], f"Visitor waiting: {obj.visitor_name} ({obj.organisation})", body=obj.purpose, severity="warning",
               resource="gate.myvisit", object_id=obj.pk, next_action="Approve or reject the visit", dedupe_key=f"visit-host:{obj.pk}")
        audit.record("visit_approval_requested", "gate.visit", obj)
        return obj

    @staticmethod
    def decide(request, obj, approve, note):
        if obj.status != "awaiting_approval":
            raise BusinessRuleError("Visit is not awaiting approval.", "invalid_state")
        if obj.created_by_id == request.user.pk:
            raise BusinessRuleError("You created this visit at the gate; the host must approve it.", "self_approval")
        if obj.host_id != request.user.pk and not has_perm(request.user, "gate.visit.approve"):
            raise BusinessRuleError("Only the assigned host or security supervisor can decide.", "not_authorised")
        obj.status = "approved" if approve else "rejected"
        obj.approved_by = request.user
        obj.decision_at = timezone.now()
        obj.decision_note = note[:300]
        obj.row_version += 1
        obj.save()
        audit.record("visit_" + obj.status, "gate.visit", obj, reason=note)
        notify_perm("gate.visit.enter", f"Visit {obj.status}: {obj.visitor_name}", resource="gate.visit", object_id=obj.pk, dedupe_key=f"visit-decided:{obj.pk}")
        return obj

    def _approve(request, obj, data):
        return VisitResource.decide(request, obj, True, data.get("note", ""))

    def _reject(request, obj, data):
        return VisitResource.decide(request, obj, False, data.get("reason", ""))

    def _enter(request, obj, data):
        require_photo(obj, "entry_photo", "Entry")
        if not obj.badge_no:
            raise BusinessRuleError("Issue a badge number before entry.", "badge_required")
        if not obj.safety_briefing_ack:
            raise BusinessRuleError("Record the safety briefing acknowledgement.", "safety_ack_required")
        obj.status = "inside"
        obj.entry_at = timezone.now()
        obj.entry_guard = request.user
        obj.row_version += 1
        obj.save()
        audit.record("visit_entered", "gate.visit", obj)
        return obj

    def _exit(request, obj, data):
        require_photo(obj, "exit_photo", "Exit")
        obj.status = "exited"
        obj.exit_at = timezone.now()
        obj.exit_guard = request.user
        obj.badge_returned = bool(data.get("badge_returned"))
        if obj.entry_at and obj.exit_at - obj.entry_at > datetime.timedelta(minutes=obj.expected_minutes + 30):
            obj.late_stay_reason = data.get("late_stay_reason", obj.late_stay_reason)
        obj.row_version += 1
        obj.save()
        audit.record("visit_exited", "gate.visit", obj, changes={"badge_returned": obj.badge_returned})
        if not obj.badge_returned:
            notify_perm("gate.visit.approve", f"Badge {obj.badge_no} not returned ({obj.visitor_name})", severity="warning",
                        resource="gate.visit", object_id=obj.pk, dedupe_key=f"badge:{obj.pk}")
        return obj

    def _cancel(request, obj, data):
        obj.status = data.get("outcome") if data.get("outcome") in {"cancelled", "no_show"} else "cancelled"
        obj.decision_note = data["reason"][:300]
        obj.save()
        audit.record("visit_" + obj.status, "gate.visit", obj, reason=data["reason"])
        return obj

    actions = [
        Action("request_approval", "Request host approval", _request, tone="primary", available=lambda o, r: o.status == "draft"),
        Action("approve", "Approve visit", _approve, available=lambda o, r: o.status == "awaiting_approval",
               fields=[{"name": "note", "label": "Note / permitted area", "type": "text"}]),
        Action("reject", "Reject visit", _reject, reason_required=True, tone="danger", available=lambda o, r: o.status == "awaiting_approval"),
        Action("enter", "Record entry", _enter, tone="primary", available=lambda o, r: o.status == "approved"),
        Action("exit", "Record exit", _exit, available=lambda o, r: o.status == "inside",
               fields=[{"name": "badge_returned", "label": "Badge returned", "type": "boolean"},
                       {"name": "late_stay_reason", "label": "Late stay reason", "type": "text"}]),
        Action("cancel", "Cancel / no-show", _cancel, permission="gate.visit.update", reason_required=True, tone="danger",
               fields=[{"name": "outcome", "label": "Outcome", "type": "choice", "choices": [{"value": "cancelled", "label": "Cancelled"}, {"value": "no_show", "label": "No show"}]}],
               available=lambda o, r: o.status in {"draft", "awaiting_approval", "approved"}),
    ]


