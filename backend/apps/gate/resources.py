    closed_states = {"exited"}
    list_fields = ["doc_no", "vehicle_no", "driver_name", "transporter", "purpose", "in_at", "out_at", "status"]
    form_fields = ["vehicle_no", "driver_name", "driver_phone", "transporter", "purpose", "seal_no"]
    filter_fields = ["status", "purpose"]
    search_fields = ["doc_no", "vehicle_no", "driver_name"]
    field_permissions = {"driver_phone": PERSONAL}
    inlines = [{"resource": "gate.gatematerial", "fk": "trip", "label": "Material entries"}]

    def before_create(self, request, data):
        data.update(in_at=timezone.now(), guard=request.user)
        data["vehicle_no"] = data["vehicle_no"].upper().replace(" ", "")

    def edit_block_reason(self, request, obj):
        return "Vehicle exited." if obj.status == "exited" else None

    def _exit(request, obj, data):
        # Vehicle may leave after unloading while material QC/discrepancy stays open (p.39).
        pending_out = obj.materials.filter(direction="out").exclude(status__in=["verified", "departed", "cancelled"])
        if pending_out.exists():
            raise BusinessRuleError("Outward load on this vehicle is not verified/authorised.", "unauthorised_load")
        obj.materials.filter(direction="out", status="verified").update(status="departed", event_at=timezone.now())
        obj.status = "exited"
        obj.out_at = timezone.now()
        obj.save()
        open_disc = obj.materials.filter(direction="in").exclude(status__in=["closed", "cancelled"]).count()
        audit.record("vehicle_exited", "gate.vehicletrip", obj, changes={"open_inward_entries": open_disc})
        return obj

    actions = [Action("exit", "Record vehicle exit", _exit, permission="gate.vehicletrip.update", tone="primary", available=lambda o, r: o.status == "inside")]


