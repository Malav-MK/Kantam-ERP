class GateEventResource(GateResource):
    key = "gate.gateevent"
    model = GateEvent
    label = "Staff / labour movement"
    singular = "Gate event"
    title_field = "kind"
    ordering = ["-at"]
    allow_update = False
    list_fields = ["person", "kind", "at", "gate", "purpose", "guard", "shift_date", "shift"]
    form_fields = ["person", "kind", "gate", "purpose", "duty_pass"]
    filter_fields = ["person", "kind", "shift_date"]
    search_fields = ["person__name", "person__person_code"]
    help = {"boundary": "Gate events feed an attendance exception queue; an entry does not prove hours worked or approve payroll."}

    def before_create(self, request, data):
        now = timezone.now()
        person = data["person"]
        slot = shift_for(now)
        data.update(at=now, guard=request.user, shift_date=slot.shift_date, shift=slot.shift)
        if not person.active:
            AttendanceException.objects.get_or_create(person=person, shift_date=slot.shift_date, kind="inactive_id", defaults={"detail": f"{data['kind']} attempted"})
            raise BusinessRuleError("Inactive person ID. Exception recorded for HR/security review.", "inactive_id")
        last = GateEvent.objects.filter(person=person).order_by("-at").first()
        if last and last.kind == data["kind"] and (now - last.at).total_seconds() < 120:
            AttendanceException.objects.get_or_create(person=person, shift_date=slot.shift_date, kind="repeat_tap", defaults={"detail": "Repeated within 2 minutes"})
            raise BusinessRuleError("Repeated tap ignored (same movement within 2 minutes).", "repeat_tap")
        if last and data["kind"] == "entry" and last.kind in {"entry", "break_in", "duty_in"}:
            AttendanceException.objects.get_or_create(person=person, shift_date=last.shift_date, kind="missing_exit",
                                                      defaults={"detail": f"No exit after {timezone.localtime(last.at):%d-%b %H:%M}"})
        if data["kind"] in {"exit", "break_out", "duty_out"} and (last is None or last.kind in {"exit", "break_out", "duty_out"}):
            AttendanceException.objects.get_or_create(person=person, shift_date=slot.shift_date, kind="missing_entry", defaults={"detail": "Exit without recorded entry"})


