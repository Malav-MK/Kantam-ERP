class GateMaterialResource(GateResource):
    key = "gate.gatematerial"
    model = GateMaterial
    label = "Material in / out"
    singular = "Gate material entry"
    closed_states = {"closed", "cancelled", "departed"}
    list_fields = ["doc_no", "direction", "inward_type", "party_name", "supplier", "document_no", "status", "trip", "dispatch", "packages", "event_at"]
    create_only_fields = ["direction", "trip", "dispatch"]
    form_fields = ["inward_type", "supplier", "customer", "party_name", "document_no", "document_date", "po_reference", "receiving_department",
                   "packages", "seal_no", "weighbridge_ref", "remarks"]
    readonly_fields = ["guard", "authorised_by"]
    filter_fields = ["direction", "status", "supplier", "trip"]
    search_fields = ["doc_no", "document_no", "party_name", "po_reference"]
    inlines = [{"resource": "gate.gatematerialline", "fk": "entry", "label": "Lines"}, {"resource": "purchase.grn", "fk": "gate_entry", "label": "GRNs"}]
    help = {
        "steps": "Inward: arrival -> receiver notified -> unloading -> stores count -> GRN -> QC. Outward: dispatch posted -> load authorised -> guard verifies -> departure.",
        "boundary": "The guard cannot increase usable stock, change commercial quantity or release QC. Stock is relieved at dispatch posting, never at gate checkout.",
    }

    def before_create(self, request, data):
        data.update(guard=request.user, event_at=timezone.now())
        if data["direction"] == "out":
            data["status"] = "arrived"
            d = data.get("dispatch")
            if d is None:
                raise BusinessRuleError("Outward material must reference the authorising dispatch record.", "authorisation_required")
            data.setdefault("customer", d.customer)
            data.setdefault("party_name", d.customer.name)

    def edit_block_reason(self, request, obj):
        if obj.status in self.closed_states:
            return f"Entry is {obj.get_status_display()}."
        if obj.direction == "out" and obj.status in {"authorised", "verified"}:
            return "Authorised load: quantities cannot be changed at the gate."
        return None

    def _set(status, requires=None, photo=None):
        def handler(request, obj, data):
            if requires and obj.status not in requires:
                raise BusinessRuleError(f"Not allowed from '{obj.get_status_display()}'.", "invalid_state")
            if photo:
                require_photo(obj, photo[0], photo[1])
            before = obj.status
            obj.status = status
            obj.event_at = timezone.now()
            obj.row_version += 1
            obj.save()
            audit.record("gate_material_" + status, "gate.gatematerial", obj, changes={"status": [before, status]}, reason=data.get("reason", ""))
            if status == "receiver_notified":
                notify_perm("purchase.grn.create", f"Material arrived: {obj.party_name or obj.supplier} {obj.document_no}", resource="gate.gatematerial",
                            object_id=obj.pk, next_action="Count / weigh and post GRN", dedupe_key=f"gate-in:{obj.pk}")
            return obj
        return handler

    def _authorise(request, obj, data):
        if obj.direction != "out":
            raise BusinessRuleError("Only outward entries need load authorisation.", "invalid_state")
        if not obj.dispatch_id or obj.dispatch.status not in {"posted", "delivered"}:
            raise BusinessRuleError("The dispatch must be posted before the gate-out is authorised.", "dispatch_not_posted")
        obj.status = "authorised"
        obj.authorised_by = request.user
        obj.save()
        audit.record("gate_out_authorised", "gate.gatematerial", obj)
        return obj

    def _verify(request, obj, data):
        if obj.status != "authorised":
            raise BusinessRuleError("An unauthorised load cannot be cleared by a guard.", "unauthorised_load")
        require_photo(obj, "challan", "Challan")
        require_photo(obj, "load", "Load")
        counted = int(data.get("packages_counted") or 0)
        if counted != obj.packages:
            obj.status = "discrepancy"
            obj.remarks = (obj.remarks + f"\nGuard counted {counted} packages vs {obj.packages} authorised").strip()
            obj.save()
            audit.record("gate_out_discrepancy", "gate.gatematerial", obj, changes={"counted": counted, "authorised": obj.packages})
            notify_perm("gate.gatematerial.authorise", f"Outward package mismatch {obj.doc_no}", severity="critical", resource="gate.gatematerial",
                        object_id=obj.pk, next_action="Resolve before departure", dedupe_key=f"gate-out-disc:{obj.pk}")
            raise BusinessRuleError(f"Package count {counted} does not match authorised {obj.packages}. Clearance blocked.", "quantity_mismatch")
        obj.status = "verified"
        obj.event_at = timezone.now()
        obj.save()
        audit.record("gate_out_verified", "gate.gatematerial", obj)
        return obj

    actions = [
        Action("arrive", "Notify receiver", _set("receiver_notified", {"arrived"}, ("invoice", "Invoice / challan")), tone="primary",
               available=lambda o, r: o.direction == "in" and o.status == "arrived"),
        Action("permit_unloading", "Permit unloading", _set("unloading", {"receiver_notified"}), permission="gate.gatematerial.arrive",
               available=lambda o, r: o.direction == "in" and o.status == "receiver_notified"),
        Action("handover", "Stores received handover", _set("handed_over", {"unloading", "receiver_notified"}), tone="primary",
               available=lambda o, r: o.direction == "in" and o.status in {"unloading", "receiver_notified"}),
        Action("discrepancy", "Record discrepancy", _set("discrepancy"), permission="gate.gatematerial.handover", reason_required=True, tone="danger",
               available=lambda o, r: o.status not in {"closed", "cancelled", "departed"}),
        Action("close", "Close (resolved)", _set("closed", {"handed_over", "discrepancy"}), permission="gate.gatematerial.handover", reason_required=True,
               available=lambda o, r: o.status in {"handed_over", "discrepancy"}),
        Action("authorise", "Authorise gate-out", _authorise, tone="primary", available=lambda o, r: o.direction == "out" and o.status in {"arrived", "discrepancy"}),
        Action("verify", "Guard verify load", _verify, tone="primary", fields=[{"name": "packages_counted", "label": "Packages counted", "type": "integer", "required": True}],
               available=lambda o, r: o.direction == "out" and o.status == "authorised"),
        Action("depart", "Record departure", _set("departed", {"verified"}), available=lambda o, r: o.direction == "out" and o.status == "verified"),
    ]


